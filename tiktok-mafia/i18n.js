/**
 * ЯЗЫК ЭФИРА.
 *
 *     STREAM_LANG=en node server.js     — эфир на Европу и США
 *     STREAM_LANG=ru node server.js     — русский (по умолчанию)
 *
 * Не LANG: это системная локаль, она почти всегда выставлена (C.UTF-8,
 * en_US.UTF-8) и включала бы английский эфир сама собой.
 *
 * Локализация живёт в данных: персонажи, места и отношения получают
 * имена на языке эфира ещё при загрузке, поэтому движок, голосование
 * в чате и память между партиями работают с ними без переводов на лету.
 * Пульт оператора (консоль) остаётся русским.
 */

const LANG = /^en/i.test(process.env.STREAM_LANG || '') ? 'en' : 'ru';

/** Строка для эфира: tr('УТРО', 'MORNING') */
const tr = (ru, en) => (LANG === 'en' ? en : ru);

module.exports = { LANG, tr };
