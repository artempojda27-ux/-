/**
 * Готовит промпты для генерации портретов.
 *
 *   node make-prompts.js > assets/PROMPTS.md
 *
 * Портреты делаются ОДИН РАЗ и живут вечно — в этом весь смысл постоянного
 * каста. Ничего не генерится на лету: в эфире это и дорого, и медленно,
 * и лица поплывут от кадра к кадру.
 *
 * Главное требование — одинаковый стиль у всех четырнадцати. Поэтому
 * общая приставка стиля жёстко одна и та же, меняется только описание человека.
 */
const { CAST } = require('./characters');

const STYLE =
  'портрет по грудь, строго анфас, ровный однотонный ярко-зелёный фон, ' +
  'стилизованный объёмный рендер как в мобильных играх, крупные выразительные ' +
  'черты, кинематографический боковой свет, контровой свет по краю силуэта, ' +
  'приглушённая тёплая палитра, без текста, без рамки, вертикальный кадр 3:4';

// Зелёный фон — не каприз: prepare_art.py вырезает его начисто, а такого
// цвета в персонаже нет, так что просветы между рукой и телом тоже уйдут.
// Контровой свет обязателен: он отбивает силуэт, без него вырезка в комнате
// выглядит наклеенной.

const STATES = [
  ['', 'спокойное лицо, губы сомкнуты, смотрит в камеру'],
  ['-talk', 'рот приоткрыт, говорит, лицо оживлённое'],
  ['-angry', 'нахмурен, напряжён, раздражён'],
];

console.log('# Портреты персонажей\n');
console.log('Три файла на персонажа в `assets/chars/`. Если файла нет — сцена');
console.log('сама покажет монограмму, так что можно начинать с одного `.png`.\n');
console.log('## Как не развалить каст\n');
console.log('Генерируй всех в одном сеансе и с одной приставкой стиля.\n');
console.log('Состояния `-talk` и `-angry` делай **редактированием спокойного кадра**,');
console.log('а не новой генерацией: «тот же персонаж, тот же свет, тот же фон,');
console.log('рот открыт, говорит». Новая генерация по тексту даст другое лицо,');
console.log('и лип-синк превратится в мельтешение двух разных людей.\n');
console.log('Первого персонажа сделай эталоном и дальше прикладывай его');
console.log('как референс стиля к остальным тринадцати.\n');
console.log('Готовые картинки — в `art_in/`, потом `python3 prepare_art.py`:');
console.log('он вырежет фон, приведёт всех к одному росту и разложит по именам.\n');

for (const c of CAST) {
  console.log(`## ${c.name} — ${c.bio}\n`);
  for (const [suffix, state] of STATES) {
    console.log(`\`assets/chars/${c.slug}${suffix}.png\``);
    console.log('```');
    console.log(`${c.look}, ${state}, ${STYLE}`);
    console.log('```');
  }
  console.log('');
}

console.log('## Фоны\n');
console.log('`assets/bg-day.jpg`');
console.log('```');
console.log('пустая гостиная старого особняка днём, длинный стол, восемь стульев, высокие окна, приглушённый свет, без людей, вертикальный кадр');
console.log('```');
console.log('`assets/bg-night.jpg`');
console.log('```');
console.log('та же гостиная старого особняка ночью, свет только от свечей, глубокие тени, холодный синий отсвет из окон, без людей, вертикальный кадр');
console.log('```');
